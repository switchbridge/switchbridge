export type PlatformType = 'telegram' | 'discord' | 'slack' | 'whatsapp' | 'webhook' | string;

export interface MessageAttachment {
  type: 'image' | 'video' | 'audio' | 'voice' | 'document' | 'sticker';
  url?: string;
  buffer?: Buffer;
  mimeType?: string;
  fileName?: string;
  fileSizeBytes?: number;
}

export interface MessageAuthor {
  id: string;                      // Native ID on the platform (e.g. Telegram user ID)
  username?: string;
  displayName: string;
  avatarUrl?: string;
  isBot?: boolean;
}

export interface UnifiedMessage {
  id: string;                      // Unique ID generated by Switchbridge
  platform: PlatformType;          // Origin platform
  channelId: string;               // Native chat/channel ID
  author: MessageAuthor;
  text: string;
  attachments?: MessageAttachment[];
  replyToMessageId?: string;
  timestamp: Date;
  raw?: any;                       // Original raw payload from the messenger SDK
  metadata?: Record<string, any>;  // Custom tags, bridge traces, user segments
}

export interface OutboundMessage {
  platform: PlatformType;
  channelId: string;
  text: string;
  attachments?: MessageAttachment[];
  replyToMessageId?: string;
  metadata?: Record<string, any>;
}
